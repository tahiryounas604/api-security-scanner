"""Report writers: JSON + Markdown for a ScanResult."""

from __future__ import annotations

import json
from dataclasses import asdict

from .scanner import ScanResult


def report_to_dict(result: ScanResult) -> dict:
    """Serialisable dict for the JSON report."""
    data = asdict(result)
    data["summary"] = result.summary
    return data


def write_json_report(result: ScanResult, path: str) -> None:
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(report_to_dict(result), handle, indent=2)
        handle.write("\n")


def write_markdown_report(result: ScanResult, path: str) -> None:
    summary = result.summary
    lines: list[str] = []
    lines.append("# API Security Scan Report")
    lines.append("")
    lines.append(f"**Target:** `{result.target}`")
    lines.append(f"**Scanned:** {result.started_at} UTC "
                 f"(took {result.duration_seconds}s)")
    lines.append("")
    lines.append("## Summary")
    lines.append("")
    lines.append("| Severity | Count |")
    lines.append("|----------|-------|")
    lines.append(f"| High | {summary['High']} |")
    lines.append(f"| Medium | {summary['Medium']} |")
    lines.append(f"| Low | {summary['Low']} |")
    lines.append(f"| **Total** | **{summary['total']}** |")
    lines.append("")
    lines.append("## Endpoints checked")
    lines.append("")
    if result.checked_endpoints:
        for endpoint in result.checked_endpoints:
            public = " (public)" if endpoint["public"] else ""
            lines.append(f"- `{endpoint['method']} {endpoint['path']}`{public}")
    else:
        lines.append("- _none_")
    lines.append("")
    lines.append("## Findings")
    lines.append("")
    if not result.findings:
        lines.append("No findings. That means these six checks passed on this "
                     "target — it is not a guarantee the API is secure.")
        lines.append("")
    else:
        for severity in ("High", "Medium", "Low"):
            group = [f for f in result.findings if f.severity == severity]
            if not group:
                continue
            lines.append(f"### {severity} ({len(group)})")
            lines.append("")
            for finding in group:
                lines.append(f"#### {finding.title}")
                lines.append("")
                lines.append(f"- **Check:** `{finding.check}`")
                lines.append(f"- **Endpoint:** `{finding.method} {finding.endpoint}`")
                lines.append(f"- **Evidence:** `{finding.evidence}`")
                lines.append(f"- **Recommendation:** {finding.recommendation}")
                lines.append("")
    if result.notes:
        lines.append("## Notes")
        lines.append("")
        for note in result.notes:
            lines.append(f"- {note}")
        lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("_Generated by api-security-scanner v0.1.0 (Tytechlabs). "
                 "Scan only targets you are authorised to test._")
    lines.append("")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
